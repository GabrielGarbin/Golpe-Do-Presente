-- Golpe do Presente - esquema inicial (Supabase / PostgreSQL)
-- Aplicar com:  supabase db push   (ou colar no SQL Editor do painel do Supabase)

-- ---------------------------------------------------------------------------
-- Clientes: pessoas que usam o sistema e fazem denúncias
-- ---------------------------------------------------------------------------
create table if not exists public.clientes (
    id        bigint generated by default as identity primary key,
    nome      text,
    email     text,
    telefone  text
);

-- ---------------------------------------------------------------------------
-- Golpistas: base colaborativa. O telefone (só dígitos, DDD + número) é único.
-- ---------------------------------------------------------------------------
create table if not exists public.golpistas (
    id                      bigint generated by default as identity primary key,
    nome                    text        not null default 'Desconhecido',
    email                   text,
    telefone                varchar(11) not null,
    total_denuncias         integer     not null default 0,
    status                  varchar(20) not null default 'SUSPEITO',
    data_primeira_denuncia  timestamp,
    data_ultima_denuncia    timestamp,
    constraint golpistas_telefone_unico   unique (telefone),
    constraint golpistas_telefone_formato check (telefone ~ '^[0-9]{10,11}$'),
    constraint golpistas_total_positivo   check (total_denuncias >= 0),
    constraint golpistas_status_valido    check (status in ('SUSPEITO', 'CONFIRMADO'))
);

-- ---------------------------------------------------------------------------
-- Denúncias: uma por cliente por número (impede inflar a contagem).
-- Excluir o cliente mantém a denúncia (cliente_id vira nulo);
-- excluir o golpista apaga as denúncias dele.
-- ---------------------------------------------------------------------------
create table if not exists public.denuncias (
    id                          bigint generated by default as identity primary key,
    cliente_id                  bigint references public.clientes (id) on delete set null,
    golpista_id                 bigint not null references public.golpistas (id) on delete cascade,
    canal                       varchar(30) not null default 'OUTRO',
    estabelecimento_falsificado text,
    descricao                   varchar(500),
    data                        timestamp not null default now(),
    constraint denuncias_cliente_golpista_unico unique (cliente_id, golpista_id),
    constraint denuncias_canal_valido check (
        canal in ('WHATSAPP', 'SMS', 'LIGACAO', 'ENTREGADOR_PRESENCIAL', 'OUTRO'))
);

create index if not exists denuncias_golpista_idx on public.denuncias (golpista_id);
create index if not exists golpistas_status_idx   on public.golpistas (status);

-- ---------------------------------------------------------------------------
-- Segurança: as tabelas do schema "public" ficam expostas pela API REST do
-- Supabase para quem tiver a chave publishable (que é pública). Com RLS ligado
-- e sem nenhuma policy, essa chave NÃO lê nem grava nada aqui; só o back-end
-- Spring (que conecta como "postgres", dono das tabelas) tem acesso.
-- Isso protege e-mails e telefones dos clientes.
-- ---------------------------------------------------------------------------
alter table public.clientes  enable row level security;
alter table public.golpistas enable row level security;
alter table public.denuncias enable row level security;
